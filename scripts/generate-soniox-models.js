#!/usr/bin/env node
/**
 * Generate Soniox model constants from the official models documentation
 *
 * The OpenAPI GetModelsResponse example can lag current model releases.
 * Soniox's models page is authoritative for current models and aliases.
 *
 * Run: node scripts/generate-soniox-models.js
 */

const fs = require("node:fs")
const path = require("node:path")

const MODELS_DOC_PATH = path.join(__dirname, "../specs/soniox-models.mdx")
const OUTPUT_PATH = path.join(__dirname, "../src/generated/soniox/models.ts")

function getSection(markdown, heading) {
  const marker = `## ${heading}`
  const start = markdown.indexOf(marker)
  if (start === -1) {
    throw new Error(`Could not find '${marker}' in Soniox models documentation`)
  }

  const nextHeading = markdown.indexOf("\n## ", start + marker.length)
  return markdown.slice(start, nextHeading === -1 ? markdown.length : nextHeading)
}

function getModelName(id) {
  const isRealtime = id.startsWith("stt-rt-")
  const version = id.replace(/^stt-(?:rt|async)-/, "")
  return `Speech-to-Text ${isRealtime ? "Real-time" : "Async"} ${version}`
}

function parseModels(markdown) {
  const currentSection = getSection(markdown, "Current models")
  const aliasesSection = getSection(markdown, "Aliases")
  const models = []

  const currentRow =
    /^\s*\|\s*\*\*(stt-(?:rt|async)-[a-z0-9-]+)\*\*\s*\|\s*(Real-time|Async)\s*\|\s*\*\*Active\*\*\s*\|/gim
  for (const match of currentSection.matchAll(currentRow)) {
    models.push({
      id: match[1],
      name: getModelName(match[1]),
      transcription_mode: match[2].toLowerCase() === "real-time" ? "real_time" : "async"
    })
  }

  const aliasRow =
    /^\s*\|\s*\*\*(stt-(?:rt|async)-[a-z0-9-]+)\*\*\s*\|\s*`(stt-(?:rt|async)-[a-z0-9-]+)`\s*\|/gim
  for (const match of aliasesSection.matchAll(aliasRow)) {
    models.push({
      id: match[1],
      name: getModelName(match[1]),
      transcription_mode: match[1].startsWith("stt-rt-") ? "real_time" : "async",
      aliased_model_id: match[2]
    })
  }

  if (models.length === 0) {
    throw new Error("Could not parse current Soniox models or aliases")
  }

  const uniqueIds = new Set(models.map((model) => model.id))
  if (uniqueIds.size !== models.length) {
    throw new Error("Soniox models documentation contains duplicate model IDs")
  }

  return models
}

function main() {
  console.log("📦 Generating Soniox model constants from official documentation...")

  if (!fs.existsSync(MODELS_DOC_PATH)) {
    console.error(`❌ Soniox models documentation not found: ${MODELS_DOC_PATH}`)
    console.error("   Run 'pnpm openapi:sync:soniox' first to download it.")
    process.exit(1)
  }

  const models = parseModels(fs.readFileSync(MODELS_DOC_PATH, "utf-8"))
  console.log(`   Found ${models.length} current models and aliases`)

  // Separate real-time and async models
  const rtModels = models.filter((m) => m.transcription_mode === "real_time")
  const asyncModels = models.filter((m) => m.transcription_mode === "async")

  console.log(`   - ${rtModels.length} real-time models`)
  console.log(`   - ${asyncModels.length} async models`)

  // Helper to convert model ID to valid JS identifier
  // e.g., "stt-rt-v5" -> "stt_rt_v5"
  const toIdentifier = (id) => id.replace(/-/g, "_")

  // Generate TypeScript file
  const output = `/**
 * Generated from Soniox models documentation - DO NOT EDIT MANUALLY
 *
 * This file is auto-generated by scripts/generate-soniox-models.js
 * Run 'pnpm openapi:sync-soniox-models' to regenerate.
 *
 * @generated
 */

/**
 * Soniox model metadata
 * Derived from https://soniox.com/docs/stt/models
 */
export const SonioxModels = [
${models
  .map(
    (m) =>
      `  { id: "${m.id}", name: "${m.name}", mode: "${m.transcription_mode}"${m.aliased_model_id ? `, aliasOf: "${m.aliased_model_id}"` : ""} }`
  )
  .join(",\n")}
] as const

/**
 * Soniox model IDs
 */
export const SonioxModelCodes = [
${models.map((m) => `  "${m.id}"`).join(",\n")}
] as const

/**
 * Type for Soniox model codes
 */
export type SonioxModelCode = (typeof SonioxModelCodes)[number]

/**
 * Real-time streaming model IDs
 */
export const SonioxRealtimeModelCodes = [
${rtModels.map((m) => `  "${m.id}"`).join(",\n")}
] as const

/**
 * Type for Soniox real-time model codes
 */
export type SonioxRealtimeModelCode = (typeof SonioxRealtimeModelCodes)[number]

/**
 * Async/batch model IDs
 */
export const SonioxAsyncModelCodes = [
${asyncModels.map((m) => `  "${m.id}"`).join(",\n")}
] as const

/**
 * Type for Soniox async model codes
 */
export type SonioxAsyncModelCode = (typeof SonioxAsyncModelCodes)[number]

/**
 * Model ID to display name mapping
 */
export const SonioxModelLabels: Record<SonioxModelCode, string> = {
${models.map((m) => `  "${m.id}": "${m.name}"`).join(",\n")}
} as const

/**
 * Soniox model constant object for autocomplete
 *
 * @example
 * \`\`\`typescript
 * import { SonioxModel } from 'voice-router-dev/constants'
 *
 * // Real-time streaming
 * { model: SonioxModel.stt_rt_v5 }
 *
 * // Async/batch transcription
 * { model: SonioxModel.stt_async_v5 }
 * \`\`\`
 */
export const SonioxModel = {
${models.map((m) => `  ${toIdentifier(m.id)}: "${m.id}"`).join(",\n")}
} as const satisfies Record<string, SonioxModelCode>

/**
 * Real-time models only (for streaming)
 */
export const SonioxRealtimeModel = {
${rtModels.map((m) => `  ${toIdentifier(m.id)}: "${m.id}"`).join(",\n")}
} as const satisfies Record<string, SonioxRealtimeModelCode>

/**
 * Async models only (for batch transcription)
 */
export const SonioxAsyncModel = {
${asyncModels.map((m) => `  ${toIdentifier(m.id)}: "${m.id}"`).join(",\n")}
} as const satisfies Record<string, SonioxAsyncModelCode>
`

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_PATH)
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true })
  }

  fs.writeFileSync(OUTPUT_PATH, output, "utf-8")
  console.log(`✅ Generated ${OUTPUT_PATH}`)
  console.log(`   - ${models.length} model codes`)
  console.log(
    "   - SonioxModels, SonioxModelCodes, SonioxModelCode, SonioxModelLabels, SonioxModel"
  )
  console.log("   - SonioxRealtimeModel, SonioxAsyncModel (separated by mode)")
}

main()
